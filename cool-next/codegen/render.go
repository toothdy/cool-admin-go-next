func componentProvider(graph *Graph, component Component) Provider {
	for _, provider := range graph.providers {
		if provider.module == component.module && provider.packagePath == component.packagePath && provider.name == component.name &&
			(provider.kind == ProviderKindComponent || provider.kind == ProviderKindConsumerDefinition) {
			return provider
		}
	}
	return Provider{}
}

func appendProvider(providers []Provider, provider Provider) []Provider {
	key := renderProviderKey(provider)
	for _, current := range providers {
		if renderProviderKey(current) == key {
			return providers
		}
	}

	return append(providers, provider)
}

func writeProvider(source *strings.Builder, provider Provider, qualified bool) {
	if qualified {
		source.WriteString("module.ProviderDefinition")
	}
	fmt.Fprintf(
		source,
		"{Kind: %s, Module: %q, PackagePath: %q, Name: %q, Type: %q}",
		moduleProviderKind(provider.kind),
		provider.module,
		provider.packagePath,
		provider.name,
		provider.typ,
	)
}

func writeReferences(source *strings.Builder, field string, references []Reference, imports *importManager) {
	var values []string
	for _, reference := range references {
		if (field == "Middlewares" && reference.group == "Middlewares") || (field == "GlobalMiddlewares" && reference.group == "GlobalMiddlewares") {
			values = append(values, strconv.Quote(reference.symbol))
		}
	}
	if len(values) == 0 {
		return
	}
	fmt.Fprintf(source, ", %s: []%s.ComponentRef{%s}", field, imports.alias(modulePackagePath), strings.Join(values, ", "))
}

func importsQualifier(imports *importManager) types.Qualifier {
	return func(pkg *types.Package) string {
		if pkg == nil {
			return ""
		}
		return imports.alias(pkg.Path())
	}
}

