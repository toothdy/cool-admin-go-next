func actionModeName(service renderService, action string) string {
	return "mode" + identifier(service.module, service.declaration.packagePath, service.declaration.name, action)
}

func actionAdapterName(service renderService, action string) string {
	return "adapter" + identifier(service.module, service.declaration.packagePath, service.declaration.name, action)
}

func serviceActionTarget(actions []ServiceAction, action string) string {
	for _, current := range actions {
		if current.name == action && current.mode != ServiceActionBase {
			return "instance." + action
		}
	}

	return "instance.Base." + action
}

func actionModeConst(mode ServiceActionMode) string {
	switch mode {
	case ServiceActionBase:
		return "Base"
	case ServiceActionOverride:
		return "Override"
	case ServiceActionDelegate:
		return "Delegate"
	default:
		return ""
	}
}

func renderError(code, message string, position Position) error {
	return &DiagnosticError{diagnostics: []Diagnostic{{Code: code, Message: message, Position: position}}}
}
